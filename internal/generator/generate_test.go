package generator

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// genProject is a project with just enough for Generate: go.mod, the orm
// marker file and the given model files.
func genProject(t *testing.T, models map[string]string) *Project {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"go.mod":                       "module example.com/x\n\ngo 1.26\n",
		"internal/database/orm/orm.go": "package orm\n",
		"internal/repository/.keep":    "",
	}
	for name, src := range models {
		files["internal/model/"+name] = src
	}
	for rel, content := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	p, err := FindProject(root)
	if err != nil {
		t.Fatal(err)
	}
	return p
}

const orderModel = `package model

import "time"

// Order is a row.
//
//gortisan:table shop_orders
type Order struct {
	ID        int64      ` + "`db:\"id,pk\"`" + `
	UserID    int64      ` + "`db:\"user_id\" json:\"user_id\"`" + `
	Note      *string    ` + "`db:\"note\"`" + `
	Cached    string     ` + "`json:\"-\"`" + `
	Skipped   string     ` + "`db:\"-\"`" + `
	CreatedAt time.Time  ` + "`db:\"created_at,default\"`" + `
	UpdatedAt time.Time  ` + "`db:\"updated_at,default\"`" + `
	DeletedAt *time.Time ` + "`db:\"deleted_at,default\"`" + `
}

// Money has no db tags, so it is not a table.
type Money struct {
	Amount int64
}
`

func TestGenerate(t *testing.T) {
	p := genProject(t, map[string]string{"order.go": orderModel})
	report, err := Generate(p, GenerateOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if len(report.Created) != 1 || report.Created[0] != "internal/repository/order_table_gen.go" {
		t.Fatalf("report = %+v", report)
	}
	gen, _ := os.ReadFile(filepath.Join(p.Root, "internal", "repository", "order_table_gen.go"))
	src := string(gen)
	for _, want := range []string{
		"// Code generated by gortisan generate from internal/model/order.go. DO NOT EDIT.",
		`Name:       "shop_orders"`,
		`PrimaryKey: "id"`,
		`"id",
		"user_id",
		"note",
		"created_at",
		"updated_at",
		"deleted_at",`,
		`&m.ID,
			&m.UserID,
			&m.Note,`,
		`InsertColumns: []string{
		"user_id",
		"note",
	},`,
		`m.UserID,
			m.Note,`,
		`UpdatedAtColumn:  "updated_at"`,
		`SoftDeleteColumn: "deleted_at"`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated file lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(src, "Cached") || strings.Contains(src, "Skipped") || strings.Contains(src, "Money") {
		t.Errorf("fields without a db tag must not be mapped:\n%s", src)
	}

	// Running again changes nothing, and --check passes.
	again, err := Generate(p, GenerateOptions{})
	if err != nil || len(again.Created)+len(again.Updated)+len(again.Removed) != 0 {
		t.Fatalf("second run = %+v, %v", again, err)
	}
	if _, err := Generate(p, GenerateOptions{Check: true}); err != nil {
		t.Fatalf("check on fresh files: %v", err)
	}

	// A new field makes the file stale; --check reports it without writing.
	model := filepath.Join(p.Root, "internal", "model", "order.go")
	edited := strings.Replace(orderModel, "Cached    string", "Total int64 `db:\"total\"`\n\tCached    string", 1)
	if err := os.WriteFile(model, []byte(edited), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Generate(p, GenerateOptions{Check: true}); err == nil {
		t.Fatal("check must fail when the struct changed")
	}
	updated, err := Generate(p, GenerateOptions{})
	if err != nil || len(updated.Updated) != 1 {
		t.Fatalf("update = %+v, %v", updated, err)
	}

	// Removing the model removes its generated file.
	if err := os.Remove(model); err != nil {
		t.Fatal(err)
	}
	removed, err := Generate(p, GenerateOptions{})
	if err != nil || len(removed.Removed) != 1 {
		t.Fatalf("remove = %+v, %v", removed, err)
	}
}

func TestGenerateDefaultsAndErrors(t *testing.T) {
	p := genProject(t, map[string]string{"order_item.go": "package model\n\ntype OrderItem struct {\n\tID int64 `db:\"id,pk\"`\n}\n"})
	if _, err := Generate(p, GenerateOptions{}); err != nil {
		t.Fatal(err)
	}
	gen, _ := os.ReadFile(filepath.Join(p.Root, "internal", "repository", "order_item_table_gen.go"))
	if !strings.Contains(string(gen), `var orderItemTable = orm.Table[model.OrderItem]`) || !strings.Contains(string(gen), `Name:       "order_items"`) {
		t.Errorf("without a directive the table is the plural of the type:\n%s", gen)
	}

	bad := map[string]string{
		"no pk":          "type A struct {\n\tID int64 `db:\"id\"`\n}",
		"unknown option": "type A struct {\n\tID int64 `db:\"id,pk,unique\"`\n}",
		"shared tag":     "type A struct {\n\tID int64 `db:\"id,pk\"`\n\tX, Y int `db:\"x\"`\n}",
		"unexported":     "type A struct {\n\tID int64 `db:\"id,pk\"`\n\tx int `db:\"x\"`\n}",
		"twice":          "type A struct {\n\tID int64 `db:\"id,pk\"`\n\tX int `db:\"x\"`\n\tY int `db:\"x\"`\n}",
		"bad column":     "type A struct {\n\tID int64 `db:\"Id,pk\"`\n}",
	}
	for name, body := range bad {
		p := genProject(t, map[string]string{"a.go": "package model\n\n" + body + "\n"})
		if _, err := Generate(p, GenerateOptions{}); err == nil {
			t.Errorf("%s: want an error", name)
		}
	}
}

func TestGenerateLeavesHandWrittenTables(t *testing.T) {
	p := genProject(t, map[string]string{"user.go": "package model\n\ntype User struct {\n\tID int64 `db:\"id,pk\"`\n}\n"})
	legacy := filepath.Join(p.Root, "internal", "repository", "user_repository.go")
	if err := os.WriteFile(legacy, []byte("package repository\n\nvar userTable = 1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	report, err := Generate(p, GenerateOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if len(report.Created) != 0 || len(report.Next) != 1 || !strings.Contains(report.Next[0], "written by hand") {
		t.Fatalf("report = %+v", report)
	}
}
