// generatedHeader starts every file `gortisan generate` owns. Go tools treat
// files with this line as generated.
const generatedHeader = "// Code generated by gortisan generate"

// tableDirective names the table of a model: //gortisan:table orders
const tableDirective = "//gortisan:table "

type genColumn struct {
	Column string // user_id
	Field  string // UserID
}

type tableSpec struct {
	Module     string
	File       string // order.go
	Type       string // Order
	Var        string // order (orderTable)
	Table      string // orders
	PK         string
	Columns    []genColumn
	Insert     []genColumn
	UpdatedAt  string
	SoftDelete string
}

// GenerateOptions configure Generate.
type GenerateOptions struct {
	// Check reports out-of-date files as an error instead of writing them.
	Check bool
}

// Generate writes internal/repository/<model>_table_gen.go for every struct
// in internal/model with db tags, and removes generated files whose model is
// gone. Files are only written when their content changes.
func Generate(p *Project, opts GenerateOptions) (*Report, error) {
	report := &Report{}
	if err := p.require("internal/database/orm/orm.go", "generate maps models for the orm of a project created with postgres"); err != nil {
		return report, err
	}
	specs, err := readModels(p)
	if err != nil {
		return report, err
	}

	handWritten, err := handWrittenTables(p)
	if err != nil {
		return report, err
	}

	keep := map[string]bool{}
	var stale []string
	for _, spec := range specs {
		if file, ok := handWritten[spec.Var+"Table"]; ok {
			report.next("%sTable is written by hand in %s; delete it there to let generate keep it in step with model.%s", spec.Var, file, spec.Type)
			continue
		}
		rel := "internal/repository/" + snake(spec.Type) + "_table_gen.go"
		keep[rel] = true
		content, err := render("make/table_gen.go.tmpl", spec)
		if err != nil {
			return report, err
		}
		target := filepath.Join(p.Root, filepath.FromSlash(rel))
		old, readErr := os.ReadFile(target)
		if readErr == nil && bytes.Equal(old, content) {
			continue
		}
		if opts.Check {
			stale = append(stale, rel)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return report, err
		}
		if err := os.WriteFile(target, content, 0o644); err != nil {
			return report, err
		}
		if readErr == nil {
			report.Updated = append(report.Updated, rel)
		} else {
			report.Created = append(report.Created, rel)
		}
	}

	// Remove generated files whose model no longer exists.
	gens, _ := filepath.Glob(filepath.Join(p.Root, "internal", "repository", "*_table_gen.go"))
	for _, path := range gens {
		rel := "internal/repository/" + filepath.Base(path)
		if keep[rel] || !isGenerated(path) {
			continue
		}
		if opts.Check {
			stale = append(stale, rel)
			continue
		}
		if err := os.Remove(path); err != nil {
			return report, err
		}
		report.Removed = append(report.Removed, rel)
	}

	if len(stale) > 0 {
		return report, fmt.Errorf("out of date, run gortisan generate: %s", strings.Join(stale, ", "))
	}
	return report, nil
}

func isGenerated(path string) bool {
	content, err := os.ReadFile(path)
	return err == nil && bytes.HasPrefix(content, []byte(generatedHeader))
}

// handWrittenTables finds `var xTable = orm.Table[...]` in non-generated
// repository files (projects made before generate existed).
func handWrittenTables(p *Project) (map[string]string, error) {
	found := map[string]string{}
	files, _ := filepath.Glob(filepath.Join(p.Root, "internal", "repository", "*.go"))
	fset := token.NewFileSet()
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || isGenerated(path) {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.VAR {
				continue
			}
			for _, s := range gen.Specs {
				for _, name := range s.(*ast.ValueSpec).Names {
					if strings.HasSuffix(name.Name, "Table") {
						found[name.Name] = "internal/repository/" + filepath.Base(path)
					}
				}
			}
		}
	}
	return found, nil
}

// readModels parses internal/model and returns a spec for every struct that
// has at least one db tag.
func readModels(p *Project) ([]tableSpec, error) {
	dir := filepath.Join(p.Root, "internal", "model")
	files, _ := filepath.Glob(filepath.Join(dir, "*.go"))
	slices.Sort(files)
	fset := token.NewFileSet()
	var specs []tableSpec
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, s := range gen.Specs {
				ts := s.(*ast.TypeSpec)
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				doc := ts.Doc
				if doc == nil && len(gen.Specs) == 1 {
					doc = gen.Doc
				}
				spec, ok, err := readModel(ts.Name.Name, st, doc)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", fset.Position(ts.Pos()), err)
				}
				if ok {
					spec.Module = p.Module
					spec.File = filepath.Base(path)
					specs = append(specs, spec)
				}
			}
		}
	}
	return specs, nil
}

func readModel(typeName string, st *ast.StructType, doc *ast.CommentGroup) (tableSpec, bool, error) {
	spec := tableSpec{Type: typeName, Var: camel(typeName), Table: plural(snake(typeName))}
	if doc != nil {
		for _, c := range doc.List {
			if table, ok := strings.CutPrefix(c.Text, tableDirective); ok {
				spec.Table = strings.TrimSpace(table)
			}
		}
	}
	for _, field := range st.Fields.List {
		if field.Tag == nil {
			continue
		}
		raw, err := strconv.Unquote(field.Tag.Value)
		if err != nil {
			return spec, false, err
		}
		tag, ok := reflect.StructTag(raw).Lookup("db")
		if !ok || tag == "-" {
			continue
		}
		parts := strings.Split(tag, ",")
		column := strings.TrimSpace(parts[0])
		if !identifierRE.MatchString(column) {
			return spec, false, fmt.Errorf("%s: db tag %q must start with a snake_case column name", typeName, tag)
		}
		if len(field.Names) == 0 {
			return spec, false, fmt.Errorf("%s: an embedded field cannot have a db tag; list its columns in the struct", typeName)
		}
		if len(field.Names) > 1 {
			return spec, false, fmt.Errorf("%s: fields %s share one db tag; give each its own line", typeName, names(field.Names))
		}
		name := field.Names[0].Name
		if !ast.IsExported(name) {
			return spec, false, fmt.Errorf("%s.%s: a mapped field must be exported", typeName, name)
		}
		col := genColumn{Column: column, Field: name}
		pk, dbDefault := false, false
		for _, option := range parts[1:] {
			switch strings.TrimSpace(option) {
			case "pk":
				pk = true
			case "default":
				dbDefault = true
			case "":
			default:
				return spec, false, fmt.Errorf("%s.%s: unknown db tag option %q (use pk or default)", typeName, name, option)
			}
		}
		if pk {
			if spec.PK != "" {
				return spec, false, fmt.Errorf("%s: more than one pk column", typeName)
			}
			spec.PK = column
		}
		for _, existing := range spec.Columns {
			if existing.Column == column {
				return spec, false, fmt.Errorf("%s: column %q is mapped twice", typeName, column)
			}
		}
		spec.Columns = append(spec.Columns, col)
		if !pk && !dbDefault {
			spec.Insert = append(spec.Insert, col)
		}
		switch column {
		case "updated_at":
			spec.UpdatedAt = column
		case "deleted_at":
			spec.SoftDelete = column
		}
	}
	if len(spec.Columns) == 0 {
		return spec, false, nil
	}
	if spec.PK == "" {
		return spec, false, errors.New(typeName + `: mark the primary key, e.g. ID int64 ` + "`" + `db:"id,pk"` + "`")
	}
	return spec, true, nil
}

func names(idents []*ast.Ident) string {
	var out []string
	for _, id := range idents {
		out = append(out, id.Name)
	}
	return strings.Join(out, ", ")
}
