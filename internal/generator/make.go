// EnumMember is one value of a generated enum.
type EnumMember struct {
	Name  string // Paid
	Label string // paid
	Value string // 2, or "paid" for string enums
}

var enumBases = map[string]bool{
	"string": true, "int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint8": true, "uint16": true, "uint32": true, "uint64": true,
}

func makeEnum(p *Project, name string, opts MakeOptions, report *Report) error {
	f, item, err := splitFeature("enum", name)
	if err != nil {
		return err
	}
	base := opts.Type
	if base == "" {
		base = "int64"
	}
	if !enumBases[base] {
		return fmt.Errorf("enum --type must be string or an integer type such as int64; got %q", base)
	}
	members, err := parseMembers(opts.Members, base == "string")
	if err != nil {
		return err
	}
	d := f.data(p)
	d.Type = pascal(item)
	d.Plural = pascal(plural(item))
	d.Base = base
	d.Members = members
	return renderAll(p.Root, []output{{f.Dir + "/" + item + ".go", "make/enum.go.tmpl"}}, d, opts.Force, report)
}

// parseMembers reads "pending,paid=5,sent": integers count up from 1 or from
// the previous value; string values default to the member's name.
func parseMembers(spec string, isString bool) ([]EnumMember, error) {
	var members []EnumMember
	seen := map[string]bool{}
	next := int64(1)
	for _, part := range strings.Split(spec, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		rawName, rawValue, hasValue := strings.Cut(part, "=")
		label, err := identifier("enum member", rawName)
		if err != nil {
			return nil, err
		}
		if seen[label] {
			return nil, fmt.Errorf("enum member %q is listed twice", label)
		}
		seen[label] = true
		member := EnumMember{Name: pascal(label), Label: label}
		switch {
		case isString && hasValue:
			member.Value = strconv.Quote(strings.TrimSpace(rawValue))
		case isString:
			member.Value = strconv.Quote(label)
		default:
			if hasValue {
				v, err := strconv.ParseInt(strings.TrimSpace(rawValue), 10, 64)
				if err != nil {
					return nil, fmt.Errorf("enum member %q: %q is not an integer", label, rawValue)
				}
				next = v
			}
			member.Value = strconv.FormatInt(next, 10)
			next++
		}
		members = append(members, member)
	}
	if len(members) == 0 {
		return nil, errors.New(`enum needs --members, e.g. --members "pending,paid,sent" or "user=3021,vendor"`)
	}
	return members, nil
}

func makeCache(p *Project, name string, opts MakeOptions, report *Report) error {
	if err := p.require("internal/cache/redis.go", "make:cache needs a project created with redis"); err != nil {
		return err
	}
	f, item, err := splitFeature("cache", name)
	if err != nil {
		return err
	}
	item = strings.TrimSuffix(item, "_cache")
	d := f.data(p)
	d.Type = pascal(item) + "Cache"
	d.Prefix = f.Name + ":" + item
	d.Value = opts.Type
	if d.Value == "" {
		d.Value = "string"
	}
	if err := writeOrAppend(p, f.Dir+"/cache.go", "make/cache.go.tmpl", d, report); err != nil {
		return err
	}
	report.next("build it in main.go: %s.New%s(rdb, time.Hour, load)", f.Pkg, d.Type)
	return nil
}

func makeWorker(p *Project, name string, opts MakeOptions, report *Report) error {
	if err := p.require("internal/kafka/kafka.go", "make:worker needs a project created with --with kafka"); err != nil {
		return err
	}
	f, item, err := splitFeature("worker", name)
	if err != nil {
		return err
	}
	item = strings.TrimSuffix(item, "_worker")
	d := f.data(p)
	d.Name = item
	d.Type = pascal(item)
	d.Topic, d.Group = opts.Topic, opts.Group
	if d.Topic == "" {
		d.Topic = item
	}
	if d.Group == "" {
		d.Group = f.Name + "." + item
	}
	if err := writeOrAppend(p, f.Dir+"/worker.go", "make/worker.go.tmpl", d, report); err != nil {
		return err
	}
	mainFile := "cmd/worker/main.go"
	if !p.exists(mainFile) {
		if err := renderAll(p.Root, []output{{mainFile, "make/worker_main.go.tmpl"}}, d, false, report); err != nil {
			return err
		}
	} else {
		report.next("add it to %s (import %q):\n\tcase %q:\n\t\treturn %s.New%sWorker(cfg.Kafka, logger).Run(ctx)",
			mainFile, p.Module+"/"+f.Dir, f.Pkg+"."+item, f.Pkg, d.Type)
	}
	report.next("run it: go run ./cmd/worker %s.%s   (or ./gortisan run worker -- %s.%s)", f.Pkg, item, f.Pkg, item)
	return nil
}

func makeCDC(p *Project, name string, opts MakeOptions, report *Report) error {
	if err := p.require("internal/kafka/kafka.go", "make:cdc needs a project created with --with kafka"); err != nil {
		return err
	}
	f, err := parseFeature(strings.TrimSuffix(snake(name), "_cdc"))
	if err != nil {
		return err
	}
	if err := p.require(f.Dir+"/"+f.Pkg+".go", "run make:model "+f.Name+" first"); err != nil {
		return err
	}
	d := f.data(p)
	d.Topic = opts.Topic
	if d.Topic == "" {
		d.Topic = plural(f.Name)
	}
	if err := ensure(p, []output{
		{"internal/cdc/cdc.go", "make/cdc_base.go.tmpl"},
		{"internal/cdc/cdc_test.go", "make/cdc_test.go.tmpl"},
	}, d, report); err != nil {
		return err
	}
	if err := renderAll(p.Root, []output{{f.Dir + "/cdc.go", "make/cdc.go.tmpl"}}, d, opts.Force, report); err != nil {
		return err
	}
	report.next("build it in main.go: %s.NewCDC(kafka.NewWriter(cfg.Kafka)), and call Created/Updated/Deleted after each commit", f.Pkg)
	return nil
}

