// Project is the Go module `make` writes into.
type Project struct {
	Root   string
	Module string
}

// FindProject walks up from dir to the nearest go.mod.
func FindProject(dir string) (*Project, error) {
	dir, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	for {
		gomod := filepath.Join(dir, "go.mod")
		if _, err := os.Stat(gomod); err == nil {
			module, err := readModule(gomod)
			if err != nil {
				return nil, err
			}
			return &Project{Root: dir, Module: module}, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return nil, errors.New("no go.mod in this directory or any parent; run gortisan make inside a project")
		}
		dir = parent
	}
}

func readModule(gomod string) (string, error) {
	file, err := os.Open(gomod)
	if err != nil {
		return "", err
	}
	defer file.Close()
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if rest, ok := strings.CutPrefix(line, "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	if err := scanner.Err(); err != nil {
		return "", err
	}
	return "", fmt.Errorf("%s has no module line", gomod)
}

func (p *Project) exists(rel string) bool {
	_, err := os.Stat(filepath.Join(p.Root, filepath.FromSlash(rel)))
	return err == nil
}

func (p *Project) require(path, why string) error {
	if !p.exists(path) {
		return fmt.Errorf("%s is missing; %s", path, why)
	}
	return nil
}

// MakeOptions configure Make.
type MakeOptions struct {
	Force      bool
	Table      string
	Fields     string
	SoftDelete bool
	// Type is the enum base type or the cached value type.
	Type string
	// Members are the enum values, e.g. "pending,paid=5".
	Members string
	// Topic and Group are a worker's Kafka topic and consumer group; Topic is
	// also the topic a CDC publishes to.
	Topic string
	Group string
	// Now stamps migration file names; time.Now when zero.
	Now time.Time
}

// MakeKinds are what `gortisan make` can write.
var MakeKinds = []string{
	"model", "service", "handler", "request", "response", "validator", "enum",
	"cache", "worker", "cdc", "middleware", "client", "migration",
}

// Make writes one building block of kind named name into p.
//
// Code about one subject lives in one package, internal/<feature>, split
// into focused files: <feature>.go (the model), repository.go, service.go,
// handler.go, request.go (inputs), response.go (outputs), and so on.
func Make(p *Project, kind, name string, opts MakeOptions) (*Report, error) {
	report := &Report{}
	var err error
	switch kind {
	case "model":
		err = makeModel(p, name, opts, report)
	case "service":
		err = makeService(p, name, opts, report)
	case "handler":
		err = makeHandler(p, name, report)
	case "request":
		err = makeRequest(p, name, report)
	case "response":
		err = makeResponse(p, name, report)
	case "validator":
		err = makeValidator(p, name, report)
	case "enum":
		err = makeEnum(p, name, opts, report)
	case "cache":
		err = makeCache(p, name, opts, report)
	case "worker":
		err = makeWorker(p, name, opts, report)
	case "cdc":
		err = makeCDC(p, name, opts, report)
	case "middleware":
		err = makeMiddleware(p, name, opts, report)
	case "client", "sdk":
		err = makeClient(p, name, opts, report)
	case "migration":
		err = makeMigration(p, name, opts, report)
	default:
		err = fmt.Errorf("unknown kind %q; choose from %s", kind, strings.Join(MakeKinds, ", "))
	}
	return report, err
}

// feature is a package about one subject, e.g. internal/user.
type feature struct {
	Name string // order_item
	Pkg  string // orderitem
	Dir  string // internal/orderitem
	Type string // OrderItem
}

// infraPackages are generated by create; a feature cannot take their name.
var infraPackages = map[string]bool{
	"config": true, "database": true, "server": true, "router": true, "validate": true,
	"metrics": true, "cache": true, "kafka": true, "cdc": true, "health": true,
	"middleware": true, "orm": true,
}

func parseFeature(name string) (feature, error) {
	n, err := identifier("feature", name)
	if err != nil {
		return feature{}, err
	}
	pkg := strings.ReplaceAll(n, "_", "")
	if infraPackages[pkg] {
		return feature{}, fmt.Errorf("%q is a package gortisan already uses (internal/%s); pick another name", n, pkg)
	}
	return feature{Name: n, Pkg: pkg, Dir: "internal/" + pkg, Type: pascal(n)}, nil
}

// splitFeature reads "user/list" into the feature and the item name.
func splitFeature(kind, name string) (feature, string, error) {
	f, item, ok := strings.Cut(strings.Trim(filepath.ToSlash(name), "/"), "/")
	if !ok || strings.Contains(item, "/") {
		return feature{}, "", fmt.Errorf("%s name must be <feature>/<name>, e.g. user/list; got %q", kind, name)
	}
	feat, err := parseFeature(f)
	if err != nil {
		return feature{}, "", err
	}
	n, err := identifier(kind, item)
	return feat, n, err
}

// data is what the make templates are rendered with.
type data struct {
	Module string
	Pkg    string
	Name   string
	Type   string
	Var    string

	Table      string
	Fields     []Field
	SoftDelete bool
	JSON       bool

	HasRepository bool
	HasService    bool

	Action string
	Route  string
	Field  string

	Message string
	Base    string
	Members []EnumMember
	Plural  string
	Value   string
	Prefix  string
	Topic   string
	Group   string
	Func    string

	Package   string
	Title     string
	EnvPrefix string
}

func (f feature) data(p *Project) data {
	return data{Module: p.Module, Pkg: f.Pkg, Name: f.Name, Type: f.Type, Var: camel(f.Type)}
}

// ensure writes the outputs that do not exist yet, without reporting the ones
// that do: shared files several commands need.
func ensure(p *Project, outputs []output, d any, report *Report) error {
	for _, out := range outputs {
		if p.exists(out.path) {
			continue
		}
		if err := renderAll(p.Root, []output{out}, d, false, report); err != nil {
			return err
		}
	}
	return nil
}

// ensureValidate writes internal/validate when the project has none.
func ensureValidate(p *Project, report *Report) error {
	return ensure(p, []output{
		{"internal/validate/validate.go", "create/validate.go.tmpl"},
		{"internal/validate/validate_test.go", "create/validate_test.go.tmpl"},
	}, projectData{Module: p.Module}, report)
}

func makeModel(p *Project, name string, opts MakeOptions, report *Report) error {
	if err := p.require("internal/database/orm/orm.go", "make:model needs a project created with postgres"); err != nil {
		return err
	}
	f, err := parseFeature(name)
	if err != nil {
		return err
	}
	d := f.data(p)
	d.Table = opts.Table
	if d.Table == "" {
		d.Table = plural(f.Name)
	}
	if d.Table, err = identifier("table", d.Table); err != nil {
		return err
	}
	if d.Fields, err = parseFields(opts.Fields); err != nil {
		return err
	}
	d.SoftDelete = opts.SoftDelete
	for _, field := range d.Fields {
		d.JSON = d.JSON || field.JSON
	}
	stamp := migrationStamp(opts.Now)
	if err := renderAll(p.Root, []output{
		{f.Dir + "/" + f.Pkg + ".go", "make/model.go.tmpl"},
		{f.Dir + "/repository.go", "make/repository.go.tmpl"},
		{"migrations/" + stamp + "_create_" + d.Table + "_table.up.sql", "make/create_table.up.sql.tmpl"},
		{"migrations/" + stamp + "_create_" + d.Table + "_table.down.sql", "make/create_table.down.sql.tmpl"},
	}, d, opts.Force, report); err != nil {
		return err
	}
	generated, err := Generate(p, GenerateOptions{})
	report.merge(generated)
	if err != nil {
		return err
	}
	report.next("apply migrations/%s_create_%s_table.up.sql to the database", stamp, d.Table)
	report.next("build it in main.go: %s.NewRepository(db)", f.Pkg)
	return nil
}

func makeService(p *Project, name string, opts MakeOptions, report *Report) error {
	f, err := parseFeature(strings.TrimSuffix(snake(name), "_service"))
	if err != nil {
		return err
	}
	d := f.data(p)
	d.HasRepository = p.exists(f.Dir + "/repository.go")
	if err := renderAll(p.Root, []output{{f.Dir + "/service.go", "make/service.go.tmpl"}}, d, opts.Force, report); err != nil {
		return err
	}
	if d.HasRepository {
		report.next("build it in main.go: %s.NewService(%s.NewRepository(db))", f.Pkg, f.Pkg)
	} else {
		report.next("build it in main.go: %s.NewService()", f.Pkg)
	}
	return nil
}

func makeHandler(p *Project, name string, report *Report) error {
	f, action, err := splitFeature("handler", name)
	if err != nil {
		return err
	}
	if err := ensureValidate(p, report); err != nil {
		return err
	}
	d := f.data(p)
	d.Action = pascal(action)
	d.Field = f.Type
	d.Route = "/" + plural(strings.ReplaceAll(f.Name, "_", "-"))
	d.HasService = p.exists(f.Dir + "/service.go")

	handlerFile := f.Dir + "/handler.go"
	isNew := !p.exists(handlerFile)
	if isNew {
		if err := renderAll(p.Root, []output{{handlerFile, "make/handler.go.tmpl"}}, d, false, report); err != nil {
			return err
		}
	}
	for _, step := range []struct{ file, tmpl string }{
		{handlerFile, "make/handler_action.go.tmpl"},
		{f.Dir + "/request.go", "make/request.go.tmpl"},
		{f.Dir + "/response.go", "make/response.go.tmpl"},
	} {
		if err := writeOrAppend(p, step.file, step.tmpl, d, report); err != nil {
			return err
		}
	}
	if isNew {
		args := ""
		if d.HasService {
			args = "service"
		}
		report.next("add `%s *%s.Handler` to router.Handlers and build it in main.go: %s.NewHandler(%s)", f.Type, f.Pkg, f.Pkg, args)
	}
	report.next("register the route in internal/router/router.go, e.g. v1.GET(%q, h.%s.%s)", d.Route, f.Type, d.Action)
	return nil
}

